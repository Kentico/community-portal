using CMS.ContactManagement;
using CMS.DataEngine;
using CMS.DataProtection;
using CMS.EmailLibrary;
using CMS.EmailMarketing;
using CMS.EmailMarketing.Internal;
using Kentico.Community.Portal.Core;

namespace Kentico.Community.Portal.Web.Features.Testing;

/// <summary>
/// Newsletter and consent state the newsletter specs (sign-up, Email marketing agreements) need.
/// </summary>
public class E2ENewsletterTestingService(
    IInfoProvider<ConsentInfo> consentProvider,
    IInfoProvider<ContactGroupInfo> contactGroupProvider,
    IInfoProvider<SendConfigurationInfo> sendConfigurationProvider,
    IInfoProvider<EmailConfigurationInfo> emailConfigurationProvider,
    IEmailUnsubscriptionUrlGenerator unsubscriptionUrlGenerator)
{
    /// <summary>
    /// Kentico's unsubscribe route (<c>UnsubscriptionUrlResolverEmailContentFilter</c>), the one regular
    /// emails link to.
    /// </summary>
    private const string UNSUBSCRIBE_ROUTE = "/Kentico.Emails/Unsubscribe";

    private readonly IInfoProvider<ConsentInfo> consentProvider = consentProvider;
    private readonly IInfoProvider<ContactGroupInfo> contactGroupProvider = contactGroupProvider;
    private readonly IInfoProvider<SendConfigurationInfo> sendConfigurationProvider = sendConfigurationProvider;
    private readonly IInfoProvider<EmailConfigurationInfo> emailConfigurationProvider = emailConfigurationProvider;
    private readonly IEmailUnsubscriptionUrlGenerator unsubscriptionUrlGenerator = unsubscriptionUrlGenerator;

    /// <summary>
    /// The consent texts as stored, so a spec can compare what a page renders with the admin text.
    /// </summary>
    public async Task<E2EConsentResponse?> GetConsent(string consentName, CancellationToken cancellationToken)
    {
        var consent = await consentProvider.GetAsync(consentName, cancellationToken);
        if (consent is null)
        {
            return null;
        }

        var text = await consent.GetConsentTextAsync(PortalWebSiteChannel.DEFAULT_LANGUAGE);

        return new E2EConsentResponse(consent.ConsentName, consent.ConsentDisplayName, text.ShortText, text.FullText, consent.ConsentHash);
    }

    /// <summary>
    /// The signed unsubscribe link a newsletter (regular email sent to the newsletter list) would carry
    /// for this address. Generated by Xperience's own generator, so the spec exercises Xperience's
    /// unsubscribe endpoint without sending a newsletter.
    /// </summary>
    public async Task<Result<E2EUnsubscribeUrlResponse>> GetNewsletterUnsubscribeUrl(string email, CancellationToken cancellationToken)
    {
        var list = (await contactGroupProvider.Get()
            .WhereEquals(nameof(ContactGroupInfo.ContactGroupName), E2EPrivacyTestingService.DEFAULT_RECIPIENT_LIST)
            .WhereTrue(nameof(ContactGroupInfo.ContactGroupIsRecipientList))
            .TopN(1)
            .GetEnumerableTypedResultAsync(cancellationToken: cancellationToken))
            .FirstOrDefault();
        if (list is null)
        {
            return Result.Failure<E2EUnsubscribeUrlResponse>($"Recipient list '{E2EPrivacyTestingService.DEFAULT_RECIPIENT_LIST}' was not found.");
        }

        var sendConfiguration = (await sendConfigurationProvider.Get()
            .WhereEquals(nameof(SendConfigurationInfo.SendConfigurationRecipientListID), list.ContactGroupID)
            .OrderByDescending(nameof(SendConfigurationInfo.SendConfigurationID))
            .TopN(1)
            .GetEnumerableTypedResultAsync(cancellationToken: cancellationToken))
            .FirstOrDefault();
        if (sendConfiguration is null)
        {
            return Result.Failure<E2EUnsubscribeUrlResponse>("No regular email is sent to the newsletter list.");
        }

        var emailConfiguration = await emailConfigurationProvider.GetAsync(sendConfiguration.SendConfigurationEmailConfigurationID, cancellationToken);
        if (emailConfiguration is null)
        {
            return Result.Failure<E2EUnsubscribeUrlResponse>($"Email configuration {sendConfiguration.SendConfigurationEmailConfigurationID} was not found.");
        }

        string url = await unsubscriptionUrlGenerator.GenerateSignedUrl(emailConfiguration, UNSUBSCRIBE_ROUTE, email, Guid.NewGuid(), isDraft: false);

        // Virtual path ("~/Kentico.Emails/..."); emails resolve it against the channel domain
        return new E2EUnsubscribeUrlResponse(url.TrimStart('~'), emailConfiguration.EmailConfigurationName);
    }
}

public record E2EConsentResponse(string Name, string DisplayName, string ShortText, string FullText, string Hash);

public record E2EUnsubscribeUrlRequest(string Email);

public record E2EUnsubscribeUrlResponse(string Url, string EmailConfigurationName);
